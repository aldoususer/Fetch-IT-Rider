import nodemailer from "nodemailer";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { db } from "./db";
import { ApplicationError } from "./rider-application-policy";
type Payload = { name: string; applicationId: string; vehicle?: string; services?: string; date?: string; venue?: string; instructions?: string; corrections?: string[] };
export function applicationMessage(kind: string, p: Payload) {
  const subject = kind === "ORIENTATION" ? "Your Fetch-It orientation invitation" : kind === "CORRECTIONS" ? "Your Fetch-It application needs corrections" : "Your Fetch-It services are activated";
  const date = p.date ? new Date(p.date).toLocaleString("en-PH", { timeZone: "Asia/Manila", dateStyle: "full", timeStyle: "short" }) + " (Philippine time)" : "";
  const text = `Dear ${p.name},\n\n` + (kind === "ORIENTATION"
    ? `Your documents for ${p.vehicle} — ${p.services} have been accepted.\n\nPlease attend your orientation:\nDate: ${date}\nVenue: ${p.venue}\n\n${p.instructions}\n\nYour orientation letter is attached. Activation follows completion of the required orientation and assessment.`
    : kind === "CORRECTIONS" ? `Please correct only the following items:\n\n${(p.corrections ?? []).map(item => `- ${item}`).join("\n")}\n\nSign in to the Fetch-It Rider app to replace the flagged documents or details. Accepted items remain accepted.`
    : `Your ${p.vehicle} services (${p.services}) are activated. Sign in to Fetch-It Rider to view your approved services and go online.`) + `\n\nApplication: ${p.applicationId}\n\nFetch-It Rider Onboarding Team`;
  return { subject, text };
}
export async function orientationLetter(p: Payload) {
  const pdf = await PDFDocument.create(), font = await pdf.embedFont(StandardFonts.Helvetica), bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  let page = pdf.addPage(), y = 720;
  const clean = (s: string) => s.normalize("NFKD").replace(/[^\x20-\x7e\n]/g, " ");
  function header() {
    page.drawRectangle({ x: 0, y: 752, width: 596, height: 90, color: rgb(.92, .31, .04) });
    page.drawText("Fetch-It", { x: 48, y: 795, size: 25, font: bold, color: rgb(1, 1, 1) });
    page.drawText("RIDER ORIENTATION INVITATION", { x: 48, y: 773, size: 10, font, color: rgb(1, 1, 1) });
  }
  header();
  for (const paragraph of applicationMessage("ORIENTATION", p).text.replace("Your orientation letter is attached. ", "").split("\n")) {
    let line = "";
    for (const word of clean(paragraph).split(/\s+/)) {
      // Long references also wrap; never let user input run past the margin.
      for (let part = 0; part < word.length || (part === 0 && !word.length); part += 55) {
        const piece = word.slice(part, part + 55);
        if (font.widthOfTextAtSize(line + " " + piece, 11) > 495) { draw(line); line = piece; } else line += (line ? " " : "") + piece;
      }
    }
    draw(line); y -= 5;
  }
  function draw(text: string) {
    if (y < 80) { page = pdf.addPage(); y = 720; header(); }
    page.drawText(text, { x: 48, y, size: 11, font, color: rgb(.09, .21, .18) }); y -= 17;
  }
  for (const [index, item] of pdf.getPages().entries()) item.drawText(`Generated by Fetch-It  |  ${index + 1} / ${pdf.getPageCount()}`, { x: 48, y: 38, size: 9, font, color: rgb(.4, .4, .4) });
  return Buffer.from(await pdf.save());
}
export function applicationTransport() {
  const sender = process.env.GMAIL_SENDER?.trim(), password = process.env.GMAIL_APP_PASSWORD?.replace(/\s/g, "");
  if (!sender || !/^[^\s@]+@gmail\.com$/i.test(sender) || !password || password.length < 16) throw new ApplicationError("Application email sender is not configured. The review is saved; configure the existing Gmail sender and retry.", 503);
  return { sender, transport: nodemailer.createTransport({ host: "smtp.gmail.com", port: 465, secure: true, auth: { user: sender, pass: password }, connectionTimeout: 8000, greetingTimeout: 8000, socketTimeout: 12000 }) };
}
export async function sendApplicationEmail(id: string) {
  const claim = await db.riderApplicationEmail.updateMany({ where: { id, status: { in: ["PENDING", "FAILED"] } }, data: { status: "SENDING", startedAt: new Date(), attempts: { increment: 1 }, failureCode: null } });
  if (!claim.count) return;
  const email = await db.riderApplicationEmail.findUniqueOrThrow({ where: { id } });
  let transport: ReturnType<typeof applicationTransport>["transport"] | undefined, sending = false;
  try {
    const config = applicationTransport(); transport = config.transport;
    const payload = email.payload as unknown as Payload;
    const attachments = email.kind === "ORIENTATION" ? [{ filename: "Fetch-It-Orientation-Letter.pdf", content: await orientationLetter(payload), contentType: "application/pdf" }] : [];
    sending = true;
    const result = await transport.sendMail({ from: { name: "Fetch-It", address: config.sender }, to: email.recipient, ...applicationMessage(email.kind, payload), attachments, messageId: `<application-${email.id}@fetchit.local>` });
    if (!result.accepted?.length) throw new Error("Recipient rejected");
    await db.riderApplicationEmail.update({ where: { id }, data: { status: "SENT", sentAt: new Date(), failureCode: null } });
  } catch {
    // SMTP can accept a message before a connection fails. Never blindly resend it.
    await db.riderApplicationEmail.update({ where: { id }, data: { status: sending ? "UNCERTAIN" : "FAILED", failureCode: sending ? "CHECK_MAILBOX_BEFORE_RESEND" : "SENDER_UNAVAILABLE" } });
  } finally { transport?.close(); }
}
